package com.mysite

import com.varabyte.kobweb.navigation.BasePath
import com.varabyte.kobweb.worker.Attachments
import com.varabyte.kobweb.worker.WorkerContext
import org.w3c.dom.Worker
import kotlin.js.Json
import kotlin.js.json

class CalculatePiWorker(override var onOutput: WorkerContext.(output: com.example.io.Output) -> Unit = {}) :
    com.varabyte.kobweb.worker.Worker<com.example.io.Input, com.example.io.Output> {

    private val ioSerializer = com.example.CalculatePiWorkerFactory().createIOSerializer()

    private val worker = Worker(BasePath.prependTo("/_kobweb/workers/worker-golden-generator/fqcn-override-with-package-only.js")).apply {
        onmessage = { e ->
            val json = e.data.unsafeCast<Json>()
            val outputDeserialized = try {
                ioSerializer.deserializeOutput(json["_output"] as String)
            } catch (e: Throwable) {
                console.warn(buildString {
                    append("Unable to deserialize output generated by worker, ignoring it.")
                    e.message?.let { append("\nException: $it") }
                })
                null
            }
            if (outputDeserialized != null) {
                val ctx = WorkerContext(Attachments.fromJson(json))
                ctx.onOutput(outputDeserialized)
            }
        }
    }

    override fun postInput(input: com.example.io.Input, attachments: Attachments) {
        val inputSerialized = try {
            ioSerializer.serializeInput(input)
        } catch (e: Throwable) {
            console.warn(buildString {
                append("Unable to serialize argument when calling `CalculatePiWorker.postInput(com.example.io.Input)`, ignoring the call.")
                e.message?.let { append("\nException: $it") }
            })
            null
        }
        if (inputSerialized != null) {
            worker.postMessage(
                json("_input" to inputSerialized).add(attachments.toJson()),
                attachments.toValues()
            )
        }
    }

    override fun terminate() {
        worker.terminate()
    }
}